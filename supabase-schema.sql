-- Execute no SQL Editor do SEU projeto Supabase.
-- Configure Authentication > Sign In / Providers para permitir Anonymous Sign-Ins.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 120),
  category text not null,
  venue text not null,
  neighborhood text,
  event_date text not null,
  price_label text not null default 'Consulte o organizador',
  description text not null default '',
  address text not null default '',
  latitude double precision,
  longitude double precision,
  emoji text not null default '✨',
  color text not null default '#D9D5FF',
  status text not null default 'published' check (status in ('draft','pending','published','cancelled')),
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint valid_latitude check (latitude is null or latitude between -90 and 90),
  constraint valid_longitude check (longitude is null or longitude between -180 and 180)
);

create index if not exists events_status_created_at_idx on public.events(status, created_at desc);
create index if not exists events_coordinates_idx on public.events(latitude, longitude);

alter table public.events enable row level security;

-- Qualquer usuário pode consultar apenas eventos publicados.
drop policy if exists "Published events are readable by everyone" on public.events;
create policy "Published events are readable by everyone"
  on public.events for select
  to anon, authenticated
  using (status = 'published');

-- Escrita requer sessão autenticada (o app usa sessão anônima do Supabase no MVP).
drop policy if exists "Authenticated users can create events" on public.events;
create policy "Authenticated users can create events"
  on public.events for insert
  to authenticated
  with check (auth.uid() = created_by);

-- Donos podem atualizar seus próprios eventos.
drop policy if exists "Owners can update their events" on public.events;
create policy "Owners can update their events"
  on public.events for update
  to authenticated
  using (auth.uid() = created_by)
  with check (auth.uid() = created_by);

-- Donos podem remover seus próprios eventos.
drop policy if exists "Owners can delete their events" on public.events;
create policy "Owners can delete their events"
  on public.events for delete
  to authenticated
  using (auth.uid() = created_by);

grant select on public.events to anon, authenticated;
grant insert, update, delete on public.events to authenticated;
grant usage, select on sequence public.events_id_seq to authenticated;
